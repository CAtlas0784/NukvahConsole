#!/usr/bin/env node
/**
 * Generates src/api/generated.ts from api/contract.json (the bridge API contract).
 *   npm run api:types          # write
 *   npm run api:types -- --check   # exit 1 if generated.ts is out of date
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contract = JSON.parse(fs.readFileSync(path.join(ROOT, 'api', 'contract.json'), 'utf8'));
const target = path.join(ROOT, 'src', 'api', 'generated.ts');

const tsType = (schema, indent = '') => {
  if (!schema) return 'unknown';
  if (typeof schema === 'string') return 'unknown';
  let t;
  if (schema.$ref) t = schema.$ref.replace('#/definitions/', '');
  else if (schema.enum) t = schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  else if (schema.oneOf) t = schema.oneOf.map((s) => tsType(s, indent)).join(' | ');
  else {
    switch (schema.type) {
      case 'integer':
      case 'number':
        t = 'number';
        break;
      case 'string':
        t = 'string';
        break;
      case 'boolean':
        t = 'boolean';
        break;
      case 'null':
        t = 'null';
        break;
      case 'array':
        t = `${wrap(tsType(schema.items, indent))}[]`;
        break;
      case 'object': {
        const props = Object.entries(schema.properties ?? {});
        const req = new Set(schema.required ?? []);
        const inner = indent + '  ';
        const lines = props.map(([k, v]) => `${inner}${k}${req.has(k) ? '' : '?'}: ${tsType(v, inner)};`);
        if (schema.additionalProperties) lines.push(`${inner}[key: string]: ${tsType(schema.additionalProperties, inner)};`);
        t = lines.length ? `{\n${lines.join('\n')}\n${indent}}` : 'Record<string, never>';
        break;
      }
      default:
        t = 'unknown';
    }
  }
  return schema.nullable ? `${t} | null` : t;
};
const wrap = (t) => (/[|&]/.test(t) && !t.startsWith('{') ? `(${t})` : t);

let out = `/* eslint-disable */
// GENERATED by scripts/gen-api-types.mjs from api/contract.json. Do not edit by hand.
// Bridge API v${contract.apiVersion} at ${contract.basePath}.

`;
for (const [name, schema] of Object.entries(contract.definitions)) {
  const body = tsType(schema);
  out += body.startsWith('{') ? `export interface ${name} ${body}\n\n` : `export type ${name} = ${body};\n\n`;
}
const codes = Object.keys(contract.errors);
out += `/** Every error code the bridge returns (see api/contract.json "errors"). */\nexport type ErrorCode =\n${codes.map((c) => `  | ${JSON.stringify(c)}`).join('\n')};\n\n`;
out += `export const ERROR_STATUS: Record<ErrorCode, number | string> = {\n${codes.map((c) => `  ${c}: ${JSON.stringify(contract.errors[c].status)},`).join('\n')}\n};\n\n`;
out += `export interface RouteSpec {\n  method: 'GET' | 'POST' | 'PATCH' | 'DELETE';\n  path: string;\n  role?: 'viewer' | 'operator' | 'admin';\n  write?: boolean;\n  proposed?: string;\n  errors?: ErrorCode[];\n}\n\n`;
out += `/** All routes, relative to ${contract.basePath}. Checked against the live server's GET /routes. */\nexport const ROUTES: RouteSpec[] = ${JSON.stringify(
  contract.routes.map(({ method, path: p, role, write, proposed, errors }) => ({ method, path: p, role, write, proposed, errors })),
  null,
  2,
)};\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('src/api/generated.ts is out of date: run npm run api:types');
    process.exit(1);
  }
  console.log('generated.ts is up to date');
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote ${path.relative(ROOT, target)} (${Object.keys(contract.definitions).length} types, ${contract.routes.length} routes, ${codes.length} error codes)`);
}
